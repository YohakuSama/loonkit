#!/usr/bin/env python3
"""Build standalone Loon scripts and their plugin from shared editable sources."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ENTRIES = {
    "node-intelligence.js": "node.js",
    "network-diagnostics.js": "network.js",
    "media-unlock.js": "media.js",
}
OUTPUT = "release/diagnostics"
PLUGIN = "release/Network_Diagnostics.plugin"


def scripts(root: Path = ROOT) -> dict[str, bytes]:
    source = root / "src/diagnostics"
    shared = (source / "common.js").read_text(encoding="utf-8").rstrip()
    header = "/* Generated by scripts/build_diagnostics.py; edit src/diagnostics/. */\n"
    return {OUTPUT + "/" + name: (header + "(function () {\n\"use strict\";\n" + shared + "\n"
                                  + (source / entry).read_text(encoding="utf-8").rstrip()
                                  + "\n})();\n").encode("utf-8") for name, entry in ENTRIES.items()}


def plugin(root: Path = ROOT) -> bytes:
    spec = json.loads((root / "build/diagnostics.json").read_text())
    if set(spec) != {"script_commit", "icon_uri"} or not re.fullmatch(r"[0-9a-f]{40}", spec["script_commit"]):
        raise ValueError("diagnostics require an exact script commit")
    from runtime_assets import pinned
    pinned(spec["icon_uri"])
    template = (root / "src/diagnostics/Network_Diagnostics.plugin").read_text(encoding="utf-8")
    return template.replace("{{SCRIPT_COMMIT}}", spec["script_commit"]).replace("{{ICON_URI}}", spec["icon_uri"]).encode("utf-8")


def build(root: Path = ROOT, *, write: bool = False, scripts_only: bool = False) -> None:
    outputs = scripts(root)
    if not scripts_only:
        outputs[PLUGIN] = plugin(root)
    for name, data in outputs.items():
        path = root / name
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.is_file() or path.read_bytes() != data:
            raise ValueError("generated diagnostics differ from source: " + name)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    operation = parser.add_mutually_exclusive_group(required=True)
    operation.add_argument("--write", action="store_true")
    operation.add_argument("--check", action="store_true")
    parser.add_argument("--scripts-only", action="store_true")
    args = parser.parse_args()
    build(write=args.write, scripts_only=args.scripts_only)
